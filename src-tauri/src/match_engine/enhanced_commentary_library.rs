/// Enhanced 1888-89 Football League Commentary Library
/// Rich, historically accurate, context-aware commentary with dynamic probability weighting
/// Tied to match state, AI decisions, team strength, player performance, and environmental factors

use std::collections::HashMap;

/// Macro to create CommentaryVariant with optional fields defaulting to None
macro_rules! variant {
    ($text:expr, $prob:expr, $triggers:expr, $priority:expr, $unique:expr) => {
        CommentaryVariant {
            text: $text.to_string(),
            base_probability: $prob,
            context_triggers: $triggers,
            priority: $priority,
            is_unique: $unique,
            team_specific: None,
            minute_range: None,
        }
    };
}

#[derive(Clone, Debug)]
pub struct CommentaryVariant {
    pub text: String,
    pub base_probability: f32,  // 0.0-1.0 base chance of occurrence
    pub context_triggers: Vec<CommentaryContext>,  // When this is more likely
    pub priority: u8,  // 1-3, higher = more impactful
    pub is_unique: bool,  // Only happens once per match
    pub team_specific: Option<String>,  // If Some, only plays for that team (e.g., "Aston Villa")
    pub minute_range: Option<(i32, i32)>,  // If Some, only plays within this minute range (0-45 for 1st half, 45-90 for 2nd half)
}

impl Default for CommentaryVariant {
    fn default() -> Self {
        CommentaryVariant {
            text: String::new(),
            base_probability: 0.0,
            context_triggers: vec![],
            priority: 1,
            is_unique: false,
            team_specific: None,
            minute_range: None,
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub enum CommentaryContext {
    // Team state
    HomeWinning,
    AwayWinning,
    TiedScore,

    // Player state
    PlayerScored,
    PlayerInjured,
    PlayerExcelling,
    PlayerStruggling,

    // Weather conditions
    HeavyRain,
    Snow,
    Wind,
    Fog,
    Darkness,
    SunInEyes,

    // Pitch conditions
    MuddyPitch,
    WaterloggedPitch,
    FrozenGround,

    // Match progression
    EarlyGame,      // 0-20 minutes
    MidGame,        // 20-65 minutes
    LateGame,       // 65-85 minutes
    FinalMinutes,   // 85-90 minutes
    HalfTime,

    // Crowd state
    CrowdExcited,
    CrowdAngry,
    CrowdNervous,
    CrowdBored,

    // Team tactics
    HomeAttacking,
    HomeDefending,
    AwayAttacking,
    AwayDefending,

    // Fatigue levels
    FreshTeams,
    TiredTeams,
    UnbalancedFatigue,

    // Match intensity
    HighIntensity,
    LowIntensity,
    BalancedPlay,

    // Abandonment buildup
    AbandonmentRisk,
    ConditionsDeteriorating,
    VeryDangerous,
}

