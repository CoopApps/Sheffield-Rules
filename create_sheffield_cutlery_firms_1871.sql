-- Create table for Sheffield cutlery firms active in 1871
-- Based on Sheffield Libraries Archives and Information document
-- Logic: active_in_1867 = 1 if:
--   1. earliest_year <= 1867 AND latest_year >= 1867 (spans 1867), OR
--   2. latest_year >= 1857 (activity within 10 years before 1867)

CREATE TABLE IF NOT EXISTS sheffield_cutlery_firms_1871 (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    active_in_1867 INTEGER NOT NULL CHECK(active_in_1867 IN (0, 1)),
    earliest_known_year INTEGER,
    latest_known_year INTEGER,
    notes TEXT
);

